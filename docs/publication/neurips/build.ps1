# Rebuild the NeurIPS-template report: figures -> visual atlas -> two PDFs -> copy both into the Zenodo package.
#   main.pdf            submission: main text, appendices A-D, NeurIPS checklist (no atlas)
#   main_reference.pdf  reference:  the same plus the visual atlas
# The reference PDF is compiled from a generated two-line wrapper (main_reference.tex) that defines
# \buildreference and inputs main.tex; main.tex turns that into \referencetrue.
# Tectonic lives at E:\tools\tectonic and keeps its package cache on E:.
$ErrorActionPreference = 'Stop'
$env:TECTONIC_CACHE_DIR = 'E:\tools\tectonic\cache'
$env:PYTHONIOENCODING = 'utf-8'
$root = Resolve-Path "$PSScriptRoot\..\..\.."
Set-Location $PSScriptRoot
$env:PYTHONPATH = "$root\.tmp\pylib"   # working fontTools copy (the C: install is broken)
$ErrorActionPreference = 'Continue'   # tools write harmless notices (e.g. Fontconfig) to stderr; check exit codes instead
python make_figures.py;  if ($LASTEXITCODE) { throw "make_figures.py failed" }
python make_atlas.py;    if ($LASTEXITCODE) { throw "make_atlas.py failed" }

$tectonic = 'E:\tools\tectonic\tectonic.exe'

# 1. submission PDF
& $tectonic -X compile --keep-logs main.tex 2>&1 | Where-Object { "$_" -notmatch 'Fontconfig' }
if ($LASTEXITCODE) { throw "tectonic failed on main.tex; see main.log" }

# 2. reference PDF (adds the atlas)
$wrapper = "% Generated by build.ps1: reference build of main.tex (adds the visual atlas). Do not edit.`n\def\buildreference{}`n\input{main}`n"
[System.IO.File]::WriteAllText("$PSScriptRoot\main_reference.tex", $wrapper, (New-Object System.Text.UTF8Encoding($false)))
& $tectonic -X compile --keep-logs main_reference.tex 2>&1 | Where-Object { "$_" -notmatch 'Fontconfig' }
if ($LASTEXITCODE) { throw "tectonic failed on main_reference.tex; see main_reference.log" }

# Layout gate: every main-text page must end at a sentence end (floats are pinned; pages may run short).
python check_page_breaks.py main.pdf
if ($LASTEXITCODE) { Write-Warning "mid-sentence page break(s) in main.pdf: fix them before submitting (see check_page_breaks.py)" }

Copy-Item main.pdf ..\zenodo\S2WISH_PAIEC2026_technical_report.pdf -Force
Copy-Item main_reference.pdf ..\zenodo\S2WISH_PAIEC2026_technical_report_with_atlas.pdf -Force
Write-Host "built main.pdf and main_reference.pdf and copied both to docs/publication/zenodo/"
